-- Levelift initial schema (week 1).
--
-- Security model:
--   * RLS is enabled on every table.
--   * Browsers (anon / authenticated roles) can only READ, and only what the
--     policies below allow. The one exception: a player may update their own
--     profiles.display_name.
--   * All game-state changes (rewards, purchases, upgrades, friendships) will
--     happen inside SECURITY DEFINER functions added in later migrations, so a
--     client can never forge Gold, Materials, XP or levels.
--
-- All currency, XP, level and score values are integers.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.profiles (
  id            uuid primary key references auth.users (id) on delete cascade,
  username      text not null unique
                  check (username ~ '^[a-z0-9_]{3,20}$'),
  display_name  text not null
                  check (char_length(display_name) between 1 and 30),
  level         integer not null default 1 check (level >= 1),
  xp            integer not null default 0 check (xp >= 0),
  created_at    timestamptz not null default now()
);
comment on table public.profiles is 'One row per player. Created automatically on sign-up.';
comment on column public.profiles.username is 'Unique, lowercase. Used to add friends.';

create table public.characters (
  user_id           uuid primary key references public.profiles (id) on delete cascade,
  outfit            text not null default 'starter',
  unlocked_outfits  text[] not null default array['starter'],
  check (unlocked_outfits <@ array['starter', 'ranger', 'knight', 'mage']),
  check (outfit = any (unlocked_outfits))
);

create table public.wallets (
  user_id    uuid primary key references public.profiles (id) on delete cascade,
  gold       integer not null default 0 check (gold >= 0),
  materials  integer not null default 0 check (materials >= 0)
);
comment on table public.wallets is 'Fictional, non-redeemable in-game currency. Only changed by server functions.';

create table public.kingdoms (
  user_id        uuid primary key references public.profiles (id) on delete cascade,
  grid_width     integer not null default 5 check (grid_width between 1 and 20),
  grid_height    integer not null default 5 check (grid_height between 1 and 20),
  kingdom_score  integer not null default 0 check (kingdom_score >= 0),
  created_at     timestamptz not null default now()
);

create table public.building_definitions (
  type            text primary key,
  name            text not null,
  max_level       integer not null check (max_level >= 1),
  -- costs[0] = purchase price, costs[n] = price to upgrade to level n + 1.
  -- Each element: {"gold": int, "materials": int}
  costs           jsonb not null,
  -- score_by_level[1] = kingdom score at level 1 (Postgres arrays are 1-based).
  score_by_level  integer[] not null,
  check (jsonb_typeof(costs) = 'array' and jsonb_array_length(costs) = max_level),
  check (array_length(score_by_level, 1) = max_level)
);

create table public.owned_buildings (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.profiles (id) on delete cascade,
  type        text not null references public.building_definitions (type),
  level       integer not null default 1 check (level >= 1),
  -- Upper bounds (the kingdom's grid size) are checked by the purchase function.
  x           integer not null check (x >= 0),
  y           integer not null check (y >= 0),
  created_at  timestamptz not null default now(),
  unique (user_id, x, y)
);
create index owned_buildings_user_id_idx on public.owned_buildings (user_id);

create table public.workouts (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null references public.profiles (id) on delete cascade,
  type               text not null check (type in ('running', 'walking', 'cycling', 'strength')),
  started_at         timestamptz not null,
  duration_minutes   integer not null check (duration_minutes between 1 and 600),
  distance_km        numeric(6, 2) check (distance_km >= 0 and distance_km <= 300),
  sets               integer check (sets between 1 and 100),
  gold_awarded       integer not null default 0 check (gold_awarded >= 0),
  materials_awarded  integer not null default 0 check (materials_awarded >= 0),
  xp_awarded         integer not null default 0 check (xp_awarded >= 0),
  -- Generated by the client per submission; makes retries award rewards only once.
  client_request_id  uuid not null,
  created_at         timestamptz not null default now(),
  unique (user_id, client_request_id)
);
create index workouts_user_started_idx on public.workouts (user_id, started_at desc);

create table public.resource_transactions (
  id                 bigint generated always as identity primary key,
  user_id            uuid not null references public.profiles (id) on delete cascade,
  gold_delta         integer not null default 0,
  materials_delta    integer not null default 0,
  xp_delta           integer not null default 0,
  reason             text not null check (reason in ('workout', 'purchase', 'upgrade')),
  workout_id         uuid references public.workouts (id) on delete set null,
  owned_building_id  uuid references public.owned_buildings (id) on delete set null,
  created_at         timestamptz not null default now()
);
comment on table public.resource_transactions is 'Audit log of every Gold / Materials / XP change.';
create index resource_transactions_user_created_idx on public.resource_transactions (user_id, created_at);

create table public.friendships (
  id            uuid primary key default gen_random_uuid(),
  requester_id  uuid not null references public.profiles (id) on delete cascade,
  addressee_id  uuid not null references public.profiles (id) on delete cascade,
  status        text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at    timestamptz not null default now(),
  check (requester_id <> addressee_id)
);
-- One friendship per pair, whichever direction it was requested in.
create unique index friendships_pair_idx on public.friendships (
  least(requester_id, addressee_id),
  greatest(requester_id, addressee_id)
);
create index friendships_addressee_idx on public.friendships (addressee_id);

