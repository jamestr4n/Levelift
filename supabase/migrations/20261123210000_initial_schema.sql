-- ---------------------------------------------------------------------------
-- Sign-up: create everything a new player needs
-- ---------------------------------------------------------------------------

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username      text := lower(trim(coalesce(new.raw_user_meta_data ->> 'username', '')));
  v_display_name  text := left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), v_username), 30);
  v_hall_score    integer;
begin
  if v_username !~ '^[a-z0-9_]{3,20}$' then
    raise exception 'Invalid username "%": use 3-20 lowercase letters, numbers or underscores', v_username
      using errcode = '22023';
  end if;

  insert into public.profiles (id, username, display_name)
  values (new.id, v_username, v_display_name);

  insert into public.characters (user_id) values (new.id);
  insert into public.wallets (user_id) values (new.id);

  -- Every kingdom starts with a level-1 Town Hall in the middle of the 5x5 grid.
  select score_by_level[1] into v_hall_score
  from public.building_definitions
  where type = 'town_hall';

  insert into public.kingdoms (user_id, kingdom_score)
  values (new.id, coalesce(v_hall_score, 0));

  insert into public.owned_buildings (user_id, type, level, x, y)
  values (new.id, 'town_hall', 1, 2, 2);

  return new;
end;
$$;

revoke execute on function public.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Username availability (used by the sign-up form before submitting)
-- ---------------------------------------------------------------------------

create function public.is_username_available(name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select lower(trim(name)) ~ '^[a-z0-9_]{3,20}$'
     and not exists (
       select 1 from public.profiles where username = lower(trim(name))
     );
$$;

revoke execute on function public.is_username_available(text) from public;
grant execute on function public.is_username_available(text) to anon, authenticated;
